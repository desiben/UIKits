// Builds FACETUI-LLMS.md: a single Markdown reference of Facet UI for AI coding assistants
// (ChatGPT, Claude, Cursor, Copilot…). The component section is generated from the style guide
// registry (styleguide/assets/registry*.js), so it always matches the documented markup.
//   node scripts/build_llms.mjs
// Buyer-only: it contains component markup, so it ships in the download, never on the public site.
import fs from "node:fs"
import path from "node:path"
import vm from "node:vm"

const ROOT = path.join(path.dirname(new URL(import.meta.url).pathname), "..")
const ASSETS = path.join(ROOT, "styleguide/assets")
const win = {}
const ctx = vm.createContext({ window: win, document: { addEventListener() {}, querySelectorAll: () => [] } })
for (const f of ["registry.js", "registry-2a.js", "registry-2b.js", "registry-3.js"]) vm.runInContext(fs.readFileSync(path.join(ASSETS, f), "utf8"), ctx)

// Same grouping and order as the style guide sidebar (assets/docs.js).
const REGROUP = { "command-palette": "Navigation", kanban: "Data display", pricing: "Data display", ai: "AI", timeline: "Data display", "empty-state": "Feedback", charts: "Charts" }
const CATS = ["Actions", "Forms", "Data display", "Charts", "AI", "Feedback", "Layout", "Navigation", "Overlays"]
const R = win.FACET_REGISTRY.map((c) => ({ ...c, group: REGROUP[c.slug] || c.group }))
R.sort((a, b) => CATS.indexOf(a.group) - CATS.indexOf(b.group) || a.name.localeCompare(b.name))

const tidy = (h) => h.trim()
  .replace(/<svg class="icon([^"]*)" aria-hidden="true"><use href="#([^"]+)"\/><\/svg>/g, '<svg class="icon$1"><use href="#$2"/></svg>')
  .replace(/\n\s*\n/g, "\n")
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ")
const intro = fs.readFileSync(path.join(ROOT, "scripts/llms-intro.md"), "utf8")
const version = (fs.readFileSync(path.join(ROOT, "CHANGELOG.md"), "utf8").match(/^## \[(\d+\.\d+\.\d+)\]/m) || [])[1] || "1.3.0"

let out = intro.replace(/\{\{VERSION\}\}/g, version).replace("{{COUNT}}", String(R.length))
out += `\n## 12. Component reference (${R.length} components)\n\nGenerated from the style guide registry. For each component: what it is, the classes, attributes and JS it uses, accessibility rules, the React install command and one working HTML example (the shortest one documented). Icons are \`<svg class="icon"><use href="#name"/></svg>\` and need \`icons.js\` on the page.\n`
for (const g of CATS) {
  const items = R.filter((c) => c.group === g)
  if (!items.length) continue
  out += `\n### ${g}\n`
  for (const c of items) {
    out += `\n#### ${c.name}\n\n${c.desc}\n\n- Docs page: \`#/components/${c.slug}\`\n- Figma: ${c.figma}\n- React: \`npx facetui@latest add ${c.slug}\`\n`
    if (c.api && c.api.length) out += `\n| Name | Kind | Notes |\n|---|---|---|\n${c.api.map((r) => `| \`${cell(r[0])}\` | ${cell(r[1])} | ${cell(r[2])} |`).join("\n")}\n`
    if (c.a11y && c.a11y.length) out += `\nAccessibility:\n${c.a11y.map((a) => `- ${a}`).join("\n")}\n`
    const ex = [...c.examples].sort((a, b) => a.html.length - b.html.length)[0]
    if (ex) out += `\nExample (${ex.title}):\n\n\`\`\`html\n${tidy(ex.html)}\n\`\`\`\n`
  }
}
out += `\n---\n\nGenerated by \`node scripts/build_llms.mjs\` from Facet UI v${version}. Facet UI © 2026 ETKits. Licensed to Facet UI buyers only; do not publish this file.\n`
fs.writeFileSync(path.join(ROOT, "FACETUI-LLMS.md"), out)
console.log(`FACETUI-LLMS.md: ${R.length} components, ${Math.round(out.length / 1024)} KB`)
