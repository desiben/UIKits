#!/usr/bin/env python3
"""Build Facet UI design tokens from the Figma variable export.

Inputs  (repo-relative):
  tokens/source/palette.json       primitive OKLCH ramps (hex)
  tokens/source/figma_export.json  variables + styles exported from the Figma file
Outputs:
  tokens/facet.tokens.json         W3C Design Tokens (DTCG) format
  tokens/tokens.css                CSS custom properties with theme / brand / density selectors
  tokens/tailwind.preset.js        Tailwind CSS preset mapped to the CSS variables

Run:  python3 scripts/build_tokens.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tokens", "source")
OUT = os.path.join(ROOT, "tokens")

palette = json.load(open(os.path.join(SRC, "palette.json")))
fig = json.load(open(os.path.join(SRC, "figma_export.json")))
V = fig["vars"]

def css_name(token: str) -> str:
    """bg/primary-hover -> --bg-primary-hover ; space/0-5 -> --space-0-5"""
    return "--" + re.sub(r"[/ ]", "-", token).lower()

def ref(value):
    """Figma alias '@iris/600' -> var(--iris-600); raw values pass through."""
    if isinstance(value, str) and value.startswith("@"):
        return f"var({css_name(value[1:])})"
    return value

def px(v):
    return f"{v}px" if isinstance(v, (int, float)) and v != 0 else ("0" if v == 0 else v)

lines = []
w = lines.append
w("/* Facet UI — design tokens")
w(" * Generated by scripts/build_tokens.py from the Figma variables. Do not edit by hand.")
w(" * Themes:  <html data-theme=\"light|dark\" data-brand=\"iris|ember|lagoon|rose|cobalt|forest\" data-density=\"comfortable|compact\">")
w(" */")
w("")
# ---- Primitives
w(":root {")
w("  /* Primitives — OKLCH-derived ramps. Prefer semantic tokens in product code. */")
for fam, steps in palette.items():
    for step, hexv in steps.items():
        w(f"  --{fam}-{step}: {hexv};")
w("")
# ---- Dimension
w("  /* Dimension */")
for k, m in V["Dimension"]["vars"].items():
    val = m["Value"]
    if k == "radius/full":
        val = 9999
    w(f"  {css_name(k)}: {px(val)};")
w("")
# ---- Typography
w("  /* Typography */")
w("  --font-sans: \"Mona Sans\", ui-sans-serif, system-ui, -apple-system, \"Segoe UI\", sans-serif;")
w("  --font-mono: \"Mona Sans\", ui-monospace, \"SFMono-Regular\", Menlo, monospace;")
for s in fig["ts"]:
    slug = s["name"].lower().replace("/", "-")
    weight = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}[s["w"]]
    ls = round(s["ls"] / 100, 4)
    w(f"  --text-{slug}: {weight} {s['size']}px/{s['lh']}px var(--font-sans);")
    w(f"  --tracking-{slug}: {ls}em;")
w("")
# ---- Elevation
w("  /* Elevation */")
def shadow(effects, dark=False):
    if not effects:
        return "none"
    parts = []
    for e in effects:
        parts.append(f"{e['x']}px {e['y']}px {e['r']}px {e['s']}px {e['c']}")
    return ", ".join(parts)
for s in fig["es"]:
    if s["name"].startswith("Elevation/"):
        n = s["name"].split("/")[1].split(" ")[0]
        w(f"  --shadow-{n}: {shadow(s['effects'])};")
w("  --ring: 0 0 0 1.5px var(--bg-surface), 0 0 0 4.5px var(--border-focus);")
w("  --ring-danger: 0 0 0 1.5px var(--bg-surface), 0 0 0 4.5px var(--border-danger);")
w("  --ease-out: cubic-bezier(.2,.8,.2,1);")
w("  --duration-fast: 120ms;")
w("  --duration-base: 200ms;")
w("  /* Motion — used by motion.css (micro-interactions) */")
w("  --ease-in-out: cubic-bezier(.65,0,.35,1);")
w("  --ease-spring: cubic-bezier(.34,1.56,.64,1);   /* gentle overshoot */")
w("  --ease-bounce: cubic-bezier(.68,-0.6,.32,1.6);  /* playful, use sparingly */")
w("  --duration-instant: 80ms;")
w("  --duration-slow: 320ms;")
w("  --duration-slower: 480ms;")
w("  --lift-sm: -1px;")
w("  --lift-md: -2px;")
w("  --press-scale: .97;")
w("}")
w("")
# ---- Brand modes
brand = V["Brand"]
for i, mode in enumerate(brand["modes"]):
    sel = f'[data-brand="{mode.lower()}"]'
    if i == 0:
        sel = ":root, " + sel
    w(f"{sel} {{")
    for k, m in brand["vars"].items():
        w(f"  {css_name(k)}: {ref(m[mode])};")
    w("}")
w("")
# ---- Color modes (re-declared on any themed subtree so nested brand/theme works)
color = V["Color"]
def color_block(mode):
    out = []
    for k, m in color["vars"].items():
        v = m[mode]
        out.append(f"  {css_name(k)}: {ref(v)};")
    return out
w(':root, [data-theme="light"], [data-brand], [data-density] {')
w("  color-scheme: light;")
lines.extend(color_block("Light"))
w("}")
w('[data-theme="dark"], [data-theme="dark"] [data-brand], [data-theme="dark"] [data-density] {')
w("  color-scheme: dark;")
lines.extend(color_block("Dark"))
w("}")
w('[data-theme="dark"] [data-theme="light"] {')
w("  color-scheme: light;")
lines.extend(color_block("Light"))
w("}")
w("")
# ---- Density
den = V["Density"]
for i, mode in enumerate(den["modes"]):
    sel = f'[data-density="{mode.lower()}"]'
    if i == 0:
        sel = ":root, " + sel
    w(f"{sel} {{")
    for k, m in den["vars"].items():
        w(f"  {css_name(k)}: {px(m[mode])};")
    w("}")

open(os.path.join(OUT, "tokens.css"), "w").write("\n".join(lines) + "\n")

# ---- DTCG JSON
def dt(type_, value, desc=None):
    d = {"$type": type_, "$value": value}
    if desc:
        d["$description"] = desc
    return d

def alias(v):
    return "{" + v[1:].replace("/", ".") + "}" if isinstance(v, str) and v.startswith("@") else v

tok = {"$description": "Facet UI design tokens (DTCG). Generated from Figma variables.",
       "primitive": {}, "brand": {}, "color": {"light": {}, "dark": {}},
       "dimension": {}, "density": {}, "typography": {}, "shadow": {}}
for fam, steps in palette.items():
    tok["primitive"][fam] = {s: dt("color", h) for s, h in steps.items()}
for mode in brand["modes"]:
    tok["brand"][mode.lower()] = {k.split("/")[1]: dt("color", alias(m[mode]).replace("{", "{primitive.")) for k, m in brand["vars"].items()}
for mode in color["modes"]:
    grp = tok["color"][mode.lower()]
    for k, m in color["vars"].items():
        v = alias(m[mode])
        if isinstance(v, str) and v.startswith("{brand."):
            v = v  # resolved against the active brand mode
        elif isinstance(v, str) and v.startswith("{"):
            v = v.replace("{", "{primitive.")
        cat, name = k.split("/")
        grp.setdefault(cat, {})[name] = dt("color", v)
for k, m in V["Dimension"]["vars"].items():
    cat, name = k.split("/")
    tok["dimension"].setdefault(cat, {})[name] = dt("dimension", f"{m['Value']}px")
for mode in den["modes"]:
    tok["density"][mode.lower()] = {k.replace("/", "-"): dt("dimension", f"{m[mode]}px") for k, m in den["vars"].items()}
for s in fig["ts"]:
    weight = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}[s["w"]]
    tok["typography"][s["name"].replace("/", "-").lower()] = dt("typography", {
        "fontFamily": "Mona Sans", "fontWeight": weight, "fontSize": f"{s['size']}px",
        "lineHeight": f"{s['lh']}px", "letterSpacing": f"{round(s['ls']/100,4)}em"})
for s in fig["es"]:
    tok["shadow"][s["name"].replace("/", "-").replace(" ", "-").lower()] = dt("shadow", [
        {"offsetX": f"{e['x']}px", "offsetY": f"{e['y']}px", "blur": f"{e['r']}px", "spread": f"{e['s']}px", "color": e["c"]}
        for e in s["effects"]])
json.dump(tok, open(os.path.join(OUT, "facet.tokens.json"), "w"), indent=2)

# ---- Tailwind preset
color_keys = list(color["vars"].keys())
def tw_group(prefix):
    return {k.split("/", 1)[1]: f"var({css_name(k)})" for k in color_keys if k.startswith(prefix + "/")}
preset = {
    "darkMode": ["selector", '[data-theme="dark"]'],
    "theme": {"extend": {
        "colors": {
            # shadcn/ui-compatible aliases
            "background": "var(--bg-canvas)", "foreground": "var(--text-primary)",
            "card": {"DEFAULT": "var(--bg-surface)", "foreground": "var(--text-primary)"},
            "popover": {"DEFAULT": "var(--bg-elevated)", "foreground": "var(--text-primary)"},
            "primary": {"DEFAULT": "var(--bg-primary)", "foreground": "var(--text-on-primary)", "hover": "var(--bg-primary-hover)"},
            "secondary": {"DEFAULT": "var(--bg-secondary)", "foreground": "var(--text-primary)"},
            "muted": {"DEFAULT": "var(--bg-muted)", "foreground": "var(--text-tertiary)"},
            "accent": {"DEFAULT": "var(--bg-accent)", "foreground": "var(--text-on-accent)"},
            "destructive": {"DEFAULT": "var(--bg-danger)", "foreground": "var(--text-on-primary)"},
            "border": "var(--border-default)", "input": "var(--border-input)", "ring": "var(--border-focus)",
            # full Facet semantic groups
            "bg": tw_group("bg"), "fg": tw_group("text"), "line": tw_group("border"),
            "icon": tw_group("icon"), "chart": tw_group("chart"),
            "brand": {s: f"var(--brand-{s})" for s in ["50","100","200","300","400","500","600","700","800","900","950"]},
        },
        "borderRadius": {k.split("/")[1]: f"var({css_name(k)})" for k in V["Dimension"]["vars"] if k.startswith("radius/")},
        "spacing": {k.split("/")[1].replace("-", "."): f"var({css_name(k)})" for k in V["Dimension"]["vars"] if k.startswith("space/")},
        "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
        "boxShadow": {str(i): f"var(--shadow-{i})" for i in range(6)} | {"ring": "var(--ring)"},
        "height": {"control-sm": "var(--control-height-sm)", "control-md": "var(--control-height-md)", "control-lg": "var(--control-height-lg)"},
    }}
}
js = "/** Facet UI — Tailwind CSS preset (generated). Usage: presets: [require('./tokens/tailwind.preset.js')] */\n"
js += "module.exports = " + json.dumps(preset, indent=2) + ";\n"
open(os.path.join(OUT, "tailwind.preset.js"), "w").write(js)
print("tokens.css, facet.tokens.json, tailwind.preset.js written")

# ---- Docs metadata + copy for the style guide
meta = {"semantic": {k: {"light": v["Light"], "dark": v["Dark"]} for k, v in color["vars"].items()},
        "families": {k: list(v.keys()) for k, v in palette.items()},
        "text": fig["ts"], "space": {k: v["Value"] for k, v in V["Dimension"]["vars"].items()},
        "density": den["vars"], "effects": [e["name"] for e in fig["es"]]}
SG = os.path.join(ROOT, "styleguide", "assets")
if os.path.isdir(SG):
    open(os.path.join(SG, "tokens-meta.js"), "w").write("/* generated by scripts/build_tokens.py */\nwindow.FACET_META=" + json.dumps(meta) + ";\n")
    open(os.path.join(SG, "tokens.css"), "w").write(open(os.path.join(OUT, "tokens.css")).read())
    print("styleguide/assets/tokens.css + tokens-meta.js synced")
